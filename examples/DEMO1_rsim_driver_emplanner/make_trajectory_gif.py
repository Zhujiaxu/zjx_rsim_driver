#!/usr/bin/env python3
"""
Create a GIF showing ego trajectory, obstacles, and the global map path.

Inputs default to output/csv files generated by run_demo.py:
  - global_path_world_points.csv
  - reference_line_motion.csv
  - obstacles.csv

Outputs:
  - ego_trajectory.csv
  - ego_trajectory.gif
"""

from __future__ import annotations

import argparse
import csv
import math
from pathlib import Path

import matplotlib

matplotlib.use("Agg")

import matplotlib.pyplot as plt
from matplotlib.animation import FuncAnimation, PillowWriter


def read_global_path(path: Path):
    points = []
    with path.open("r", newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            points.append((float(row["x"]), float(row["y"])))
    return points


def read_ego_trajectory(path: Path):
    frames = {}
    with path.open("r", newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            frame_id = int(row["frame_id"])
            if frame_id in frames:
                continue
            frames[frame_id] = {
                "frame_id": frame_id,
                "sim_time": float(row["sim_time"]),
                "x": float(row["ego_x"]),
                "y": float(row["ego_y"]),
                "target_x": float(row["target_x"]),
                "target_y": float(row["target_y"]),
            }
    return [frames[key] for key in sorted(frames)]


def read_obstacles(path: Path):
    frames = {}
    if not path.is_file():
        return frames

    with path.open("r", newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            try:
                frame_id = int(row["frame_id"])
                frames.setdefault(frame_id, []).append(
                    {
                        "frame_id": frame_id,
                        "sim_time": float(row["sim_time"]),
                        "actor_id": int(row["actor_id"]),
                        "actor_name": row.get("actor_name", ""),
                        "actor_type": int(row.get("actor_type", "0")),
                        "x": float(row["x"]),
                        "y": float(row["y"]),
                        "h": float(row.get("h", "0")),
                        "length": float(row.get("length", "0")),
                        "width": float(row.get("width", "0")),
                    }
                )
            except (KeyError, ValueError):
                continue
    return frames


def write_ego_trajectory_csv(path: Path, frames):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(
            f, fieldnames=["frame_id", "sim_time", "x", "y", "target_x", "target_y"]
        )
        writer.writeheader()
        for frame in frames:
            writer.writerow(
                {
                    "frame_id": frame["frame_id"],
                    "sim_time": f"{frame['sim_time']:.9f}",
                    "x": f"{frame['x']:.9f}",
                    "y": f"{frame['y']:.9f}",
                    "target_x": f"{frame['target_x']:.9f}",
                    "target_y": f"{frame['target_y']:.9f}",
                }
            )


def sample_frames(frames, max_frames: int):
    if max_frames <= 0 or len(frames) <= max_frames:
        return frames
    if max_frames == 1:
        return [frames[0]]

    last = len(frames) - 1
    sampled = []
    seen = set()
    for i in range(max_frames):
        index = round(last * i / (max_frames - 1))
        if index not in seen:
            sampled.append(frames[index])
            seen.add(index)
    return sampled


def all_xy(points):
    return [p[0] for p in points], [p[1] for p in points]


def obstacle_box_points(obstacle):
    length = max(obstacle["length"], 0.5)
    width = max(obstacle["width"], 0.5)
    half_l = 0.5 * length
    half_w = 0.5 * width
    heading = obstacle["h"]
    cos_h = math.cos(heading)
    sin_h = math.sin(heading)
    local = [
        (half_l, half_w),
        (half_l, -half_w),
        (-half_l, -half_w),
        (-half_l, half_w),
    ]
    return [
        (obstacle["x"] + lx * cos_h - ly * sin_h,
         obstacle["y"] + lx * sin_h + ly * cos_h)
        for lx, ly in local
    ]


def obstacle_xy(obstacles):
    xs = []
    ys = []
    for obstacle in obstacles:
        xs.append(obstacle["x"])
        ys.append(obstacle["y"])
        for x, y in obstacle_box_points(obstacle):
            xs.append(x)
            ys.append(y)
    return xs, ys


def expand_limits(xs, ys, aspect: float, padding: float):
    min_x, max_x = min(xs), max(xs)
    min_y, max_y = min(ys), max(ys)
    width = max(max_x - min_x + 2.0 * padding, 20.0)
    height = max(max_y - min_y + 2.0 * padding, 12.0)

    if width / height > aspect:
        height = width / aspect
    else:
        width = height * aspect

    center_x = 0.5 * (min_x + max_x)
    center_y = 0.5 * (min_y + max_y)
    return (
        center_x - 0.5 * width,
        center_x + 0.5 * width,
        center_y - 0.5 * height,
        center_y + 0.5 * height,
    )


def draw_obstacles(ax, obstacles):
    for index, obstacle in enumerate(obstacles):
        box = obstacle_box_points(obstacle)
        closed = box + [box[0]]
        xs, ys = all_xy(closed)
        label = "obstacle" if index == 0 else None
        ax.fill(xs, ys, facecolor="#d93025", edgecolor="#d93025",
                linewidth=1.4, alpha=0.16, label=label, zorder=4)
        ax.scatter([obstacle["x"]], [obstacle["y"]], s=28,
                   color="#d93025", edgecolors="white", linewidths=0.8,
                   zorder=5)
        name = obstacle["actor_name"] or f"actor_{obstacle['actor_id']}"
        ax.text(obstacle["x"], obstacle["y"] + 0.8, name,
                fontsize=7, color="#9b1c15", ha="center", va="bottom",
                zorder=6)


def make_gif(global_csv: Path,
             motion_csv: Path,
             obstacle_csv: Path,
             trajectory_csv: Path,
             output_gif: Path,
             max_frames: int,
             fps: int,
             dpi: int):
    if not global_csv.is_file():
        raise SystemExit(f"ERROR: global path CSV not found: {global_csv}")
    if not motion_csv.is_file():
        raise SystemExit(f"ERROR: reference-line motion CSV not found: {motion_csv}")

    global_points = read_global_path(global_csv)
    trajectory = read_ego_trajectory(motion_csv)
    obstacles_by_frame = read_obstacles(obstacle_csv)
    if len(global_points) < 2:
        raise SystemExit(f"ERROR: not enough global path points: {global_csv}")
    if not trajectory:
        raise SystemExit(f"ERROR: no ego trajectory frames: {motion_csv}")

    write_ego_trajectory_csv(trajectory_csv, trajectory)
    sampled = sample_frames(trajectory, max_frames)
    output_gif.parent.mkdir(parents=True, exist_ok=True)

    fig, ax = plt.subplots(figsize=(10.5, 6.2))
    aspect = 10.5 / 6.2

    route_xs, route_ys = all_xy(global_points)
    xs = list(route_xs)
    ys = list(route_ys)
    xs.extend(frame["x"] for frame in trajectory)
    ys.extend(frame["y"] for frame in trajectory)
    if obstacles_by_frame:
        all_obstacles = [obs for rows in obstacles_by_frame.values() for obs in rows]
        obstacle_xs, obstacle_ys = obstacle_xy(all_obstacles)
        xs.extend(obstacle_xs)
        ys.extend(obstacle_ys)
    limits = expand_limits(xs, ys, aspect, padding=10.0)

    full_traj = [(frame["x"], frame["y"]) for frame in trajectory]
    sampled_traj = [(frame["x"], frame["y"]) for frame in sampled]

    def draw(frame_index: int):
        frame = sampled[frame_index]
        current_obstacles = obstacles_by_frame.get(frame["frame_id"], [])
        trail = sampled_traj[:frame_index + 1]

        ax.clear()
        ax.plot(route_xs, route_ys, color="#8a9099", linewidth=1.5,
                label="global path", zorder=1)
        if len(full_traj) >= 2:
            txs, tys = all_xy(full_traj)
            ax.plot(txs, tys, color="#f29900", linewidth=1.2, alpha=0.25,
                    label="ego full trajectory", zorder=2)
        if len(trail) >= 2:
            txs, tys = all_xy(trail)
            ax.plot(txs, tys, color="#f29900", linewidth=2.8,
                    label="ego trajectory", zorder=3)

        draw_obstacles(ax, current_obstacles)

        ax.scatter([frame["target_x"]], [frame["target_y"]], s=58,
                   color="#1a73e8", edgecolors="white", linewidths=0.8,
                   label="planner target", zorder=7)
        ax.scatter([frame["x"]], [frame["y"]], s=80,
                   color="#202124", edgecolors="white", linewidths=0.9,
                   label="ego", zorder=8)

        if frame_index > 0:
            previous = sampled[frame_index - 1]
            heading = math.atan2(frame["y"] - previous["y"],
                                 frame["x"] - previous["x"])
            ax.arrow(frame["x"], frame["y"],
                     math.cos(heading) * 3.0,
                     math.sin(heading) * 3.0,
                     width=0.16, head_width=0.9, head_length=1.2,
                     length_includes_head=True, color="#202124", zorder=9)

        ax.set_xlim(limits[0], limits[1])
        ax.set_ylim(limits[2], limits[3])
        ax.set_aspect("equal", adjustable="box")
        ax.grid(True, color="#e6e8eb", linewidth=0.8)
        ax.set_xlabel("world x (m)")
        ax.set_ylabel("world y (m)")
        ax.set_title(
            "Ego trajectory with global path and obstacles "
            f"frame={frame['frame_id']} t={frame['sim_time']:.2f}s"
        )
        ax.legend(loc="upper right", fontsize=8, framealpha=0.92)
        return []

    animation = FuncAnimation(fig,
                              draw,
                              frames=len(sampled),
                              interval=1000.0 / max(1, fps),
                              blit=False)
    writer = PillowWriter(fps=max(1, fps))
    animation.save(output_gif, writer=writer, dpi=dpi)
    plt.close(fig)

    print(f"[trajectory-gif] global points: {len(global_points)}")
    print(f"[trajectory-gif] trajectory frames: {len(trajectory)} sampled: {len(sampled)}")
    print(f"[trajectory-gif] trajectory csv: {trajectory_csv}")
    print(f"[trajectory-gif] output: {output_gif}")


def parse_args():
    here = Path(__file__).resolve().parent
    csv_dir = here / "output" / "csv"
    parser = argparse.ArgumentParser(
        description="Create ego trajectory GIF with global path and obstacles."
    )
    parser.add_argument("--global-csv",
                        type=Path,
                        default=csv_dir / "global_path_world_points.csv")
    parser.add_argument("--motion-csv",
                        type=Path,
                        default=csv_dir / "reference_line_motion.csv")
    parser.add_argument("--obstacle-csv",
                        type=Path,
                        default=csv_dir / "obstacles.csv")
    parser.add_argument("--trajectory-csv",
                        type=Path,
                        default=csv_dir / "ego_trajectory.csv")
    parser.add_argument("--output",
                        type=Path,
                        default=csv_dir / "ego_trajectory.gif")
    parser.add_argument("--max-frames",
                        type=int,
                        default=160,
                        help="Uniformly sample at most this many frames; <=0 uses all frames.")
    parser.add_argument("--fps", type=int, default=12)
    parser.add_argument("--dpi", type=int, default=110)
    return parser.parse_args()


if __name__ == "__main__":
    args = parse_args()
    make_gif(args.global_csv,
             args.motion_csv,
             args.obstacle_csv,
             args.trajectory_csv,
             args.output,
             args.max_frames,
             args.fps,
             args.dpi)
